/**
 * Messages between the page and the Alloy engine Web Worker.
 *
 * Calls are processed one at a time, in order. Analysis problems (syntax errors, no instance, ...)
 * come back as a normal `result`; `failure` means the engine itself could not run.
 */

/** Compiled engine flavour; `auto` prefers WebAssembly GC and falls back to JavaScript. */
export type AlloyBrowserBackend = 'auto' | 'wasm-gc' | 'js';

/** Must match `AlloyBrowserMain.API_VERSION` (Java) and the generated `manifest.json`. */
export const ENGINE_API_VERSION = 1;

/** Functions exported by the TeaVM-compiled engine (see `AlloyBrowserMain.java`). */
export interface CompiledAlloyEngine {
    apiVersion(): number;
    findInstance(code: string, cmd: number): string;
    nextInstance(specId: string): string;
    evaluate(specId: string, expr: string, state: number): string;
    maxRedundantSet(code: string, cmdId: number): string;
    explainRedundancyAtCursor(code: string, cursorPos: number): string;
}

export type EngineMethod = Exclude<keyof CompiledAlloyEngine, 'apiVersion'>;

/** Generated by the `installToFrontend` Gradle task next to the compiled engine. */
export interface EngineManifest {
    apiVersion: number;
    engineVersion: string;
    contentHash: string;
    wasm: string;
    wasmRuntime: string;
    js: string;
}

export type LoadedBackend = Exclude<AlloyBrowserBackend, 'auto'>;

export interface InitMessage {
    kind: 'init';
    assetBaseUrl: string;
    backend: AlloyBrowserBackend;
}

export interface CallMessage {
    kind: 'call';
    id: number;
    method: EngineMethod;
    args: Array<string | number>;
}

export type ToWorker = InitMessage | CallMessage;

export type FromWorker =
    | { kind: 'result'; id: number; json: string; backend: LoadedBackend }
    | { kind: 'failure'; id: number; message: string };
