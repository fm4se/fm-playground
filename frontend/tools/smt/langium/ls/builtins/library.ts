/**
 * The builtin library: all theory sorts and functions of SMT-LIB 2.7 and Z3.
 *
 * Builtin symbols are materialized as a small in-memory SMT-LIB document
 * (`builtin:///smt-lib-builtins.smt2`) containing one declaration per symbol, so that
 * references to builtins are ordinary Langium cross-references. Signatures and
 * documentation come from the catalog data, not from that document.
 */
import { AstUtils, URI, type AstNode, type AstNodeDescription, type AstNodeDescriptionProvider, type LangiumDocument, type LangiumDocumentFactory, type LangiumDocuments } from 'langium';
import type { LangiumServices } from 'langium/lsp';
import { isDeclareFun, isDeclareSort, type Script } from '../generated/ast.js';
import { coreFunctions, coreSorts } from './catalog-core.js';
import { extFunctions, extSorts } from './catalog-ext.js';
import type { BuiltinFunctionSpec, BuiltinSortSpec } from './types.js';
import { printSymbol } from '../typing/sorts.js';

export const BUILTIN_URI = 'builtin:///smt-lib-builtins.smt2';

/** The builtin URI as produced by `URI.toString()` (which normalizes it). */
const BUILTIN_URI_STRING = URI.parse(BUILTIN_URI).toString();

/**
 * Placeholder symbol substituted for terms that are nested too deeply to be parsed
 * (see SmtParser). It is resolvable and has an unknown sort.
 */
export const DEEP_TERM_PLACEHOLDER = '@deep';

const internalFunctions: BuiltinFunctionSpec[] = [
    { name: DEEP_TERM_PLACEHOLDER, theory: 'internal', ranks: ['-> ?'], doc: 'A term that is nested too deeply to be analysed by the language server.' },
];

export class BuiltinLibrary {

    readonly functions = new Map<string, BuiltinFunctionSpec[]>();
    readonly sorts = new Map<string, BuiltinSortSpec>();

    private readonly documents: LangiumDocuments;
    private readonly documentFactory: LangiumDocumentFactory;
    private readonly descriptionProvider: () => AstNodeDescriptionProvider;
    private document: LangiumDocument | undefined;
    private functionDescriptions = new Map<string, AstNodeDescription>();
    private sortDescriptions = new Map<string, AstNodeDescription>();

    constructor(services: LangiumServices) {
        this.documents = services.shared.workspace.LangiumDocuments;
        this.documentFactory = services.shared.workspace.LangiumDocumentFactory;
        this.descriptionProvider = () => services.workspace.AstNodeDescriptionProvider;
        for (const spec of [...coreFunctions, ...extFunctions, ...internalFunctions]) {
            const list = this.functions.get(spec.name) ?? [];
            list.push(spec);
            this.functions.set(spec.name, list);
        }
        for (const spec of [...coreSorts, ...extSorts]) {
            if (!this.sorts.has(spec.name)) this.sorts.set(spec.name, spec);
        }
    }

    /** The text of the builtin document. */
    getText(): string {
        const lines = [
            '; Builtin sorts and functions of SMT-LIB 2.7 and Z3.',
            '; This document is generated by the language server; see the hover documentation of each symbol.',
        ];
        for (const name of this.sorts.keys()) lines.push(`(declare-sort ${printSymbol(name)} 0)`);
        for (const name of this.functions.keys()) lines.push(`(declare-fun ${printSymbol(name)} () Bool)`);
        return lines.join('\n') + '\n';
    }

    /** Returns the builtin document, creating it on first use. */
    getDocument(): LangiumDocument {
        const uri = URI.parse(BUILTIN_URI);
        if (this.document && this.documents.hasDocument(uri)) return this.document;
        let document = this.documents.getDocument(uri);
        if (!document) {
            document = this.documentFactory.fromString(this.getText(), uri);
            this.documents.addDocument(document);
        }
        this.document = document;
        this.indexDocument(document);
        return document;
    }

    private indexDocument(document: LangiumDocument): void {
        this.functionDescriptions.clear();
        this.sortDescriptions.clear();
        const provider = this.descriptionProvider();
        for (const command of (document.parseResult.value as Script).commands) {
            if (isDeclareFun(command)) {
                this.functionDescriptions.set(command.name, provider.createDescription(command, command.name, document));
            } else if (isDeclareSort(command)) {
                this.sortDescriptions.set(command.name, provider.createDescription(command, command.name, document));
            }
        }
    }

    isBuiltinNode(node: AstNode): boolean {
        return AstUtils.getDocument(node).uri.toString() === BUILTIN_URI_STRING;
    }

    isBuiltinDocument(document: LangiumDocument): boolean {
        return document.uri.toString() === BUILTIN_URI_STRING;
    }

    /** Maps names of symbol families to their catalog entry, e.g. `bv42` (in `(_ bv42 8)`) to `bv`. */
    canonicalFunctionName(name: string): string {
        if (this.functions.has(name)) return name;
        if (/^bv\d+$/.test(name)) return 'bv';
        return name;
    }

    getFunctionDescription(name: string): AstNodeDescription | undefined {
        this.getDocument();
        return this.functionDescriptions.get(this.canonicalFunctionName(name));
    }

    getSortDescription(name: string): AstNodeDescription | undefined {
        this.getDocument();
        return this.sortDescriptions.get(name);
    }

    /** Builtin function descriptions offered by code completion (internal symbols excluded). */
    getAllFunctionDescriptions(): AstNodeDescription[] {
        this.getDocument();
        return [...this.functionDescriptions.values()].filter(d => d.name !== DEEP_TERM_PLACEHOLDER);
    }

    getAllSortDescriptions(): AstNodeDescription[] {
        this.getDocument();
        return [...this.sortDescriptions.values()];
    }

    /**
     * Catalog entries for a function name. When `indexed` is given, entries of the
     * matching form (indexed identifier or plain symbol) are preferred.
     */
    getFunctionSpecs(name: string, indexed?: boolean): BuiltinFunctionSpec[] {
        const specs = this.functions.get(this.canonicalFunctionName(name)) ?? [];
        if (indexed === undefined) return specs;
        const matching = specs.filter(s => (s.indices !== undefined) === indexed);
        return matching.length > 0 ? matching : specs;
    }

    getSortSpec(name: string): BuiltinSortSpec | undefined {
        return this.sorts.get(name);
    }
}
